CREATE TABLE ejercicios (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    nombre VARCHAR(100) NOT NULL,
    descripcion VARCHAR(1000) NOT NULL,
    grupo_muscular VARCHAR(80) NOT NULL,
    equipo VARCHAR(100) NOT NULL
);
CREATE TABLE rutinas (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    nombre VARCHAR(100) NOT NULL,
    descripcion VARCHAR(1000) NOT NULL,
    nivel VARCHAR(20) NOT NULL CHECK (nivel IN ('PRINCIPIANTE','INTERMEDIO','AVANZADO')),
    duracion_minutos INTEGER NOT NULL CHECK (duracion_minutos BETWEEN 1 AND 600)
);
CREATE TABLE rutina_ejercicio (
    rutina_id BIGINT NOT NULL REFERENCES rutinas(id) ON DELETE CASCADE,
    ejercicio_id BIGINT NOT NULL REFERENCES ejercicios(id) ON DELETE CASCADE,
    PRIMARY KEY (rutina_id, ejercicio_id)
);
CREATE INDEX idx_rutina_ejercicio_ejercicio ON rutina_ejercicio(ejercicio_id);
